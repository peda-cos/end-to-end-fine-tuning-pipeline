"""Data card generation from measured data statistics."""

from __future__ import annotations

from typing import Any


def render_data_card(cfg: Any, metrics: dict[str, Any]) -> str:
    data = metrics["data"]
    contamination = data["contamination"]
    return f"""# Data card — {cfg['project']['name']}

## Source

Synthetic support-ticket and policy corpus generated by `src/ftpipe/data/synth.py`; no third-party
benchmark data, web crawl, or real PII is included. Seed: `{cfg['run']['seed']}`.

## Preprocessing

1. Exact SHA-256 plus {cfg['data']['minhash']['ngram']}-word MinHash-LSH near-duplicate removal.
2. Gopher-style hard rules and a learned hashed n-gram quality classifier.
3. Presidio-style recognizers for {", ".join(cfg['data']['pii']['entities']).lower()}.
4. Seeded train/validation split with cross-split near-duplicate isolation.
5. Exact {cfg['data']['contamination']['exact_ngram']}-gram and MinHash contamination scan against benchmark-shaped fixtures.

## Counts

| Field | Value |
|---|---:|
| Raw documents | {data['raw_docs']} |
| Dedup removed | {data['dedup_removed']} |
| Quality rejected | {data['quality_rejected']} |
| PII entities removed | {data['pii_entities_removed']} |
| Training documents after cleaning | {data['train_docs']} |
| SFT train records | {data.get('sft_train_records', 0)} |
| SFT validation records | {data.get('val_docs', 0)} |
| Preference pairs | {data.get('preference_pairs', 0)} |

## Contamination

- Benchmark fixture documents: {contamination.get('benchmark_docs', 0)}
- Raw overlap detected: {contamination.get('raw_overlap_docs', contamination.get('initial_overlap_docs', 0))}
- Rejected by split scans: {contamination.get('rejected_docs', 0)}; final overlap: {contamination.get('overlap_docs', 0)}; green: {contamination.get('green')}

## Splits and intended use

SFT train/validation and preference train/validation are disjoint; evaluation fixtures are never
inserted into training. Intended for pipeline validation only. See `fixtures/README.md` for the
synthetic benchmark-shaped stand-ins.

## License

CC0-1.0 for generated data; code MIT. No real personal data.
"""
